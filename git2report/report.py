@dataclass
class CategorizedCommit:
    hash: str
    subject: str
    author: str
    date: str
    type: str  # feat, fix, perf, refactor, docs, chore, etc.
    added: int = 0
    deleted: int = 0


@dataclass
class Section:
    module: str
    text: str
    hashes: list[str]
    mode: str = "offline"
    note: str = ""
    commits: list[CategorizedCommit] = field(default_factory=list)


@dataclass
class ReportData:
    project: str
    start: str
    end: str
    audience: str
    metrics: dict
    sections: list[Section] = field(default_factory=list)
    mode_label: str = ""
    glance_text: str = ""
    in_progress: list[BranchInfo] = field(default_factory=list)
    planned: list[str] = field(default_factory=list)
    generated: str = field(default_factory=lambda: datetime.now().strftime("%Y-%m-%d %H:%M"))
    remote_url: str | None = None
    executive_summary: str = ""


def render_markdown(data: ReportData) -> str:
    return MARKDOWN.render(d=data).rstrip() + "\n"


def _esc(t: str) -> str:
    return t.replace("&", "&amp;").replace("<", "&lt;").replace(">", "&gt;")


def render_pdf(data: ReportData, path: Path) -> None:
    ss = getSampleStyleSheet()
    navy = colors.HexColor("#0F172A")
    blue = colors.HexColor("#2563EB")
    slate = colors.HexColor("#334155")
    gray_bg = colors.HexColor("#F8FAFC")
    gray_border = colors.HexColor("#CBD5E1")

    title = ParagraphStyle("t", parent=ss["Title"], fontName="Helvetica-Bold", fontSize=18, leading=22, textColor=navy, alignment=0, spaceAfter=4)
    meta = ParagraphStyle("m", parent=ss["Normal"], fontSize=8.5, leading=11, textColor=colors.HexColor("#64748B"), spaceAfter=8)
    h = ParagraphStyle("h", parent=ss["Heading2"], fontName="Helvetica-Bold", fontSize=11, leading=14, textColor=navy, spaceBefore=8, spaceAfter=3)
    body = ParagraphStyle("b", parent=ss["Normal"], fontSize=9, leading=13, textColor=slate)
    ev = ParagraphStyle("e", parent=ss["Normal"], fontName="Courier", fontSize=7.5, leading=10, textColor=colors.HexColor("#64748B"), spaceAfter=2)
    note_style = ParagraphStyle("n", parent=ss["Normal"], fontSize=8, leading=11, textColor=colors.HexColor("#B45309"), spaceAfter=2)

    cell = ParagraphStyle("c", parent=ss["Normal"], fontSize=8, leading=10.5, textColor=slate)
    cell_bold = ParagraphStyle("cb", parent=cell, fontName="Helvetica-Bold", fontSize=10.5, leading=12.5, textColor=navy)
    cellh = ParagraphStyle("ch", parent=cell, fontName="Helvetica-Bold", fontSize=8, leading=10.5, textColor=colors.white)

    m = data.metrics
    lines_add = m.get("lines_added", 0)
    lines_del = m.get("lines_deleted", 0)

    # 1. Header & Meta
    story = [
        Paragraph("Weekly Progress Report", title),
        Paragraph(
            f"Project: <b>{_esc(data.project)}</b> &nbsp;|&nbsp; Period: {data.start} to {data.end} &nbsp;|&nbsp; Audience: {data.audience.capitalize()}",
            meta
        ),
    ]

    # 2. Executive Summary (TL;DR)
    if getattr(data, "executive_summary", ""):
        exec_title = ParagraphStyle("et", parent=ss["Normal"], fontName="Helvetica-Bold", fontSize=8.5, leading=11, textColor=colors.HexColor("#1D4ED8"), spaceAfter=2)
        exec_body = ParagraphStyle("eb", parent=ss["Normal"], fontSize=8.5, leading=12.5, textColor=colors.HexColor("#1E293B"))
        exec_box = Table([
            [Paragraph("EXECUTIVE SUMMARY (TL;DR)", exec_title)],
            [Paragraph(_esc(data.executive_summary), exec_body)],
        ], colWidths=[17.4*cm])
        exec_box.setStyle(TableStyle([
            ("BACKGROUND", (0, 0), (-1, -1), colors.HexColor("#F8FAFC")),
            ("BOX", (0, 0), (-1, -1), 0.5, colors.HexColor("#E2E8F0")),
            ("LINEBEFORE", (0, 0), (0, -1), 3.0, blue),
            ("TOPPADDING", (0, 0), (-1, -1), 4),
            ("BOTTOMPADDING", (0, 0), (-1, -1), 4),
            ("LEFTPADDING", (0, 0), (-1, -1), 8),
            ("RIGHTPADDING", (0, 0), (-1, -1), 8),
        ]))
        story += [exec_box, Spacer(1, 4)]

    # 3. KPI Grid (4 Cards)
    kpi_rows = [
        [
            Paragraph("COMMITS", cell),
            Paragraph("NET CODE CHURN", cell),
            Paragraph("PRIMARY IMPACT", cell),
            Paragraph("TEST RATIO", cell),
        ],
        [
            Paragraph(f"<b>{m['commits']}</b> <font size=7 color='#64748B'>(of {m['commits_seen_before_filter']})</font>", cell_bold),
            Paragraph(f"<b>{m['lines_changed']}</b> <font size=7 color='#059669'>+{lines_add}</font> <font size=7 color='#DC2626'>-{lines_del}</font>", cell_bold),
            Paragraph(f"<b>{_esc(str(m['top_module']))}</b>", cell_bold),
            Paragraph(f"<b>{m['test_to_code_ratio']}</b>", cell_bold),
        ],
    ]
    tbl = Table(kpi_rows, colWidths=[4.35*cm, 4.45*cm, 4.4*cm, 4.2*cm])
    tbl.setStyle(TableStyle([
        ("BACKGROUND", (0, 0), (-1, -1), gray_bg),
        ("BOX", (0, 0), (-1, -1), 0.5, gray_border),
        ("INNERGRID", (0, 0), (-1, -1), 0.5, gray_border),
        ("TOPPADDING", (0, 0), (-1, -1), 5),
        ("BOTTOMPADDING", (0, 0), (-1, -1), 5),
        ("LEFTPADDING", (0, 0), (-1, -1), 7),
        ("RIGHTPADDING", (0, 0), (-1, -1), 7),
    ]))
    story += [tbl, Spacer(1, 4)]

    # 4. At-a-glance banner
    glance_box = Table([[Paragraph(f"<b>At a glance:</b> {_esc(data.glance_text)}", body)]], colWidths=[17.4*cm])
    glance_box.setStyle(TableStyle([
        ("BACKGROUND", (0, 0), (-1, -1), colors.HexColor("#EFF6FF")),
        ("BOX", (0, 0), (-1, -1), 0.5, colors.HexColor("#BFDBFE")),
        ("TOPPADDING", (0, 0), (-1, -1), 4),
        ("BOTTOMPADDING", (0, 0), (-1, -1), 4),
        ("LEFTPADDING", (0, 0), (-1, -1), 8),
        ("RIGHTPADDING", (0, 0), (-1, -1), 8),
    ]))
    story += [glance_box, Spacer(1, 4)]

    # 4b. Visual Analytics Chart: Commit Type Distribution
    commits_by_type = m.get("commits_by_type", {})
    if commits_by_type:
        from git2report.charts import build_type_breakdown_bar
        type_chart = build_type_breakdown_bar(commits_by_type, width=490, height=30)
        story += [
            Paragraph("Commit Type Distribution", h),
            type_chart,
            Spacer(1, 3)
        ]

    # 4c. Visual Analytics: Module Code Churn Chart (+Lines Added / -Lines Deleted)
    if data.sections:
        from git2report.charts import build_module_churn_chart
        churn_chart = build_module_churn_chart(data.sections, width=490, height=60)
        story += [
            Paragraph("Code Churn by Module (+Lines Added / -Lines Deleted)", h),
            churn_chart,
            Spacer(1, 4)
        ]

    # 5. Two-column Analytics: Tech Stack + Codebase Hotspots
    tech_stack = m.get("tech_stack", [])
    hotspots = m.get("hotspots", [])
    if tech_stack or hotspots:
        # Tech stack table
        ts_rows = [[Paragraph("Technology", cellh), Paragraph("Share", cellh)]]
        if isinstance(tech_stack, list):
            for item in tech_stack[:5]:
                t_name = item.get("tech", "Other") if isinstance(item, dict) else str(item)
                t_pct = item.get("percentage", 0) if isinstance(item, dict) else 0
                ts_rows.append([
                    Paragraph(_esc(str(t_name)), cell),
                    Paragraph(f"<b>{t_pct}%</b>", cell),
                ])
        elif isinstance(tech_stack, dict):
            for tech, pct in list(tech_stack.items())[:5]:
                ts_rows.append([
                    Paragraph(_esc(str(tech)), cell),
                    Paragraph(f"<b>{pct}%</b>", cell),
                ])
        if len(ts_rows) == 1:
            ts_rows.append([Paragraph("Not detected", cell), Paragraph("-", cell)])
        ts_tbl = Table(ts_rows, colWidths=[5.4*cm, 2.6*cm])
        ts_tbl.setStyle(TableStyle([
            ("BACKGROUND", (0, 0), (-1, 0), navy),
            ("ROWBACKGROUNDS", (0, 1), (-1, -1), [colors.white, gray_bg]),
            ("GRID", (0, 0), (-1, -1), 0.5, gray_border),
            ("TOPPADDING", (0, 0), (-1, -1), 2.5),
            ("BOTTOMPADDING", (0, 0), (-1, -1), 2.5),
            ("LEFTPADDING", (0, 0), (-1, -1), 5),
            ("RIGHTPADDING", (0, 0), (-1, -1), 5),
        ]))

        # Hotspots table
        hs_rows = [[Paragraph("Active File", cellh), Paragraph("Commits", cellh), Paragraph("Lines", cellh)]]
        if isinstance(hotspots, list):
            for hs in hotspots[:5]:
                if isinstance(hs, dict):
                    fname = hs.get("path") or hs.get("file", "")
                    n_commits = hs.get("commits", 0)
                    n_lines = hs.get("lines", 0)
                else:
                    fname = str(hs)
                    n_commits = 0
                    n_lines = 0
                if len(fname) > 26:
                    fname = "..." + fname[-23:]
                hs_rows.append([
                    Paragraph(f"<font face='Courier' size=7>{_esc(fname)}</font>", cell),
                    Paragraph(str(n_commits), cell),
                    Paragraph(str(n_lines), cell),
                ])
        if len(hs_rows) == 1:
            hs_rows.append([Paragraph("None", cell), Paragraph("-", cell), Paragraph("-", cell)])
        hs_tbl = Table(hs_rows, colWidths=[5.4*cm, 1.8*cm, 1.8*cm])
        hs_tbl.setStyle(TableStyle([
            ("BACKGROUND", (0, 0), (-1, 0), navy),
            ("ROWBACKGROUNDS", (0, 1), (-1, -1), [colors.white, gray_bg]),
            ("GRID", (0, 0), (-1, -1), 0.5, gray_border),
            ("TOPPADDING", (0, 0), (-1, -1), 2.5),
            ("BOTTOMPADDING", (0, 0), (-1, -1), 2.5),
            ("LEFTPADDING", (0, 0), (-1, -1), 5),
            ("RIGHTPADDING", (0, 0), (-1, -1), 5),
        ]))

        analytics_tbl = Table([
            [Paragraph("Tech Stack Breakdown", h), Paragraph("Codebase Hotspots", h)],
            [ts_tbl, hs_tbl]
        ], colWidths=[8.4*cm, 9.0*cm])
        analytics_tbl.setStyle(TableStyle([
            ("VALIGN", (0, 0), (-1, -1), "TOP"),
            ("LEFTPADDING", (0, 0), (-1, -1), 0),
            ("RIGHTPADDING", (0, 0), (-1, -1), 0),
            ("TOPPADDING", (0, 0), (-1, -1), 1),
            ("BOTTOMPADDING", (0, 0), (-1, -1), 2),
        ]))
        story += [analytics_tbl, Spacer(1, 4)]

    # 6. Team Contributor Leaderboard
    contributors = m.get("contributors", [])
    if contributors and len(contributors) > 0:
        c_rows = [[
            Paragraph("Contributor", cellh),
            Paragraph("Commits", cellh),
            Paragraph("Lines (+ / -)", cellh),
            Paragraph("Primary Focus", cellh),
        ]]
        for c_ in contributors[:6]:
            c_rows.append([
                Paragraph(_esc(c_["name"]), cell),
                Paragraph(str(c_["commits"]), cell),
                Paragraph(f"<font color='#059669'>+{c_['added']}</font> / <font color='#DC2626'>-{c_['deleted']}</font>", cell),
                Paragraph(_esc(c_["top_module"]), cell),
            ])
        c_tbl = Table(c_rows, colWidths=[5.2*cm, 2.6*cm, 4.6*cm, 5.0*cm])
        c_tbl.setStyle(TableStyle([
            ("BACKGROUND", (0, 0), (-1, 0), navy),
            ("ROWBACKGROUNDS", (0, 1), (-1, -1), [colors.white, gray_bg]),
            ("GRID", (0, 0), (-1, -1), 0.5, gray_border),
            ("TOPPADDING", (0, 0), (-1, -1), 3),
            ("BOTTOMPADDING", (0, 0), (-1, -1), 3),
            ("LEFTPADDING", (0, 0), (-1, -1), 6),
            ("RIGHTPADDING", (0, 0), (-1, -1), 6),
        ]))
        story += [Paragraph("Team Contributors", h), c_tbl, Spacer(1, 4)]

    bullet = ParagraphStyle("bl", parent=body, leftIndent=12, bulletIndent=2, fontSize=8.5, leading=12)

    # 7. Module Deliverables & Categorized Badges
    story.append(Paragraph("Module Deliverables", h))
    for s in data.sections:
        story.append(Paragraph(f"<b>{_esc(s.module)}</b>", h))
        s_box = Table([[Paragraph(_esc(s.text), body)]], colWidths=[17.4*cm])
        s_box.setStyle(TableStyle([
            ("BACKGROUND", (0, 0), (-1, -1), gray_bg),
            ("BOX", (0, 0), (-1, -1), 0.5, gray_border),
            ("LINEBEFORE", (0, 0), (0, -1), 2.5, blue),
            ("TOPPADDING", (0, 0), (-1, -1), 4),
            ("BOTTOMPADDING", (0, 0), (-1, -1), 4),
            ("LEFTPADDING", (0, 0), (-1, -1), 8),
            ("RIGHTPADDING", (0, 0), (-1, -1), 8),
        ]))
        story.append(s_box)

        # Categorized commits with distinct badge colors
        if s.commits:
            badge_colors = {
                "FEAT": "#059669",
                "FIX": "#DC2626",
                "PERF": "#7C3AED",
                "REFACTOR": "#D97706",
                "DOCS": "#0284C7",
                "STYLE": "#64748B",
                "TEST": "#0D9488",
                "CHORE": "#64748B",
            }
            commit_items = []
            for cm_ in s.commits[:5]:
                t_label = cm_.type.upper() if cm_.type else "OTHER"
                b_color = badge_colors.get(t_label, "#2563EB")
                commit_items.append(
                    Paragraph(
                        f"<font color='{b_color}'><b>[{t_label}]</b></font> {_esc(cm_.subject)} &nbsp;<font color='#64748B'>({_esc(cm_.author)}, +{cm_.added}/-{cm_.deleted})</font> <font face='Courier' color='#2563EB'>{cm_.hash}</font>",
                        bullet,
                        bulletText="\u2022"
                    )
                )
            story += commit_items
            if len(s.commits) > 5:
                story.append(Paragraph(f"<i>... and {len(s.commits) - 5} more commits</i>", bullet))

        story.append(Paragraph("Evidence: " + ", ".join(s.hashes), ev))
        if s.note:
            story.append(Paragraph("Note: " + _esc(s.note), note_style))
        story.append(Spacer(1, 3))

    # 8. In progress branches
    if data.in_progress:
        story.append(Paragraph("In progress (open branches)", h))
        for b in data.in_progress:
            story.append(Paragraph(f"<b>{_esc(b.name)}</b>: {b.ahead} commit(s) not merged yet, last activity {b.last_date} ({_esc(b.subject)})",
                                   bullet, bulletText="\u2022"))

    # 9. Planned goals
    if data.planned:
        story.append(Paragraph("Planned goals (written by the developer)", h))
        for g_ in data.planned:
            story.append(Paragraph(_esc(g_), bullet, bulletText="\u2022"))

    story += [Spacer(1, 8), Paragraph(f"Generated by Git2Report on {data.generated}. Summaries: {_esc(data.mode_label)}.", meta)]

    def header_footer(c, doc):
        c.saveState()
        c.setFont("Helvetica", 7.5)
        c.setFillColor(colors.HexColor("#64748B"))
        # Running header (pages > 1)
        if doc.page > 1:
            c.drawString(1.8*cm, A4[1] - 1.2*cm, f"{data.project} — Weekly Progress Report")
            c.drawRightString(A4[0] - 1.8*cm, A4[1] - 1.2*cm, f"Generated: {data.generated}")
            c.setStrokeColor(gray_border)
            c.setLineWidth(0.5)
            c.line(1.8*cm, A4[1] - 1.35*cm, A4[0] - 1.8*cm, A4[1] - 1.35*cm)

        # Running footer
        c.drawString(1.8*cm, 1.1*cm, "Git2Report | Engineering Delivery Report")
        c.drawRightString(A4[0] - 1.8*cm, 1.1*cm, f"Page {doc.page}")
        c.setStrokeColor(gray_border)
        c.setLineWidth(0.5)
        c.line(1.8*cm, 1.3*cm, A4[0] - 1.8*cm, 1.3*cm)
        c.restoreState()

    SimpleDocTemplate(
        str(path), pagesize=A4,
        leftMargin=1.8*cm, rightMargin=1.8*cm,
        topMargin=1.6*cm, bottomMargin=1.6*cm,
        title=f"{data.project} Progress Report"
    ).build(story, onFirstPage=header_footer, onLaterPages=header_footer)


